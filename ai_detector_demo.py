import re

def analyze_text_features(text):
    """Analyzes text for features commonly associated with AI-generated text."""
    features = {}

    # 1. Sentence Length Variation
    sentences = re.split(r'[.!?]+', text)
    sentences = [s.strip() for s in sentences if s.strip()]
    if sentences:
        sentence_lengths = [len(s.split()) for s in sentences]
        features['avg_sentence_length'] = sum(sentence_lengths) / len(sentence_lengths)
        features['sentence_length_stddev'] = (sum([(l - features['avg_sentence_length'])**2 for l in sentence_lengths]) / len(sentence_lengths))**0.5
    else:
        features['avg_sentence_length'] = 0
        features['sentence_length_stddev'] = 0

    # 2. Word Choice and Repetition (Simplified)
    words = re.findall(r'\b\w+\b', text.lower())
    if words:
        features['unique_word_ratio'] = len(set(words)) / len(words)
        # A very basic check for repetitive phrasing, AI might use similar structures
        word_counts = {} 
        for word in words:
            word_counts[word] = word_counts.get(word, 0) + 1
        features['most_common_word_freq'] = max(word_counts.values()) if word_counts else 0
    else:
        features['unique_word_ratio'] = 0
        features['most_common_word_freq'] = 0

    # 3. Predictability (Simplified - e.g., common phrases)
    # More advanced models look at token probabilities, this is a proxy
    common_phrases = ["in conclusion", "furthermore", "it is important to note"]
    phrase_density = sum(text.lower().count(phrase) for phrase in common_phrases)
    features['common_phrase_density'] = phrase_density / (len(words) + 1) # Avoid division by zero

    # 4. Punctuation Usage (Simplified)
    punctuation_count = len(re.findall(r'[.,;:]', text))
    features['punctuation_density'] = punctuation_count / (len(words) + 1)

    return features

def classify_text(features):
    """A very simplistic classifier based on analyzed features."""
    # These thresholds are illustrative and highly simplified.
    # Real detectors use complex machine learning models.
    score = 0

    # AI often has more consistent sentence lengths
    if features.get('sentence_length_stddev', 0) < 5:
        score += 1

    # AI might use a slightly lower unique word ratio
    if features.get('unique_word_ratio', 0) < 0.7:
        score += 1

    # AI might use more common transitional phrases
    if features.get('common_phrase_density', 0) > 0.05:
        score += 1

    # AI might have a slightly higher punctuation density (e.g., commas)
    if features.get('punctuation_density', 0) > 0.1:
        score += 1

    # AI might have a higher frequency of its most common word (less varied vocabulary)
    if features.get('most_common_word_freq', 0) > 5:
        score += 1

    if score >= 3: # Threshold for 'likely AI'
        return "Likely AI-generated"
    else:
        return "Likely Human-generated"

# --- Example Usage ---

# Example 1: Text likely generated by AI
# (Shorter, more consistent sentences, common phrases)
text_ai = "In conclusion, the advancements in artificial intelligence are transforming various industries. It is important to note that these technologies offer significant benefits. Furthermore, the potential for innovation is immense. We can expect to see more sophisticated applications emerge in the near future. The impact on society will be profound."

# Example 2: Text likely written by a human
# (More varied sentence lengths, less predictable phrasing)
text_human = "Wow, this AI stuff is really something else! It's amazing how fast it can churn out text. I tried asking it to write a poem about cats, and it did a pretty decent job. But sometimes, you can just tell it's not quite human, you know? Like, the way it strings sentences together can feel a bit too perfect, or maybe a bit repetitive. Still, super useful for brainstorming ideas, though."

print("--- Analyzing AI-like Text ---")
features_ai = analyze_text_features(text_ai)
print(f"Features: {features_ai}")
classification_ai = classify_text(features_ai)
print(f"Classification: {classification_ai}")

print("\n--- Analyzing Human-like Text ---")
features_human = analyze_text_features(text_human)
print(f"Features: {features_human}")
classification_human = classify_text(features_human)
print(f"Classification: {classification_human}")
